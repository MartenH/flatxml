#!/usr/bin/env python3
"""Write flatxml/xsd/unicode.v: the Unicode general category of every code point, as runs.

    python3 tools/gen_unicode.py > flatxml/xsd/unicode.v

The table is the start of each run of code points sharing a category, and the category of the
run, from the Unicode Character Database of the Python that runs this (unicodedata). The pattern
engine uses it for \\d, \\w and \\p{...}.
"""
import unicodedata

CATEGORIES = ['Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Mn', 'Mc', 'Me', 'Nd', 'Nl', 'No', 'Pc', 'Pd', 'Ps',
              'Pe', 'Pi', 'Pf', 'Po', 'Zs', 'Zl', 'Zp', 'Sm', 'Sc', 'Sk', 'So', 'Cc', 'Cf', 'Cs',
              'Co', 'Cn']

starts, cats = [], []
prev = None
for cp in range(0x110000):
    c = unicodedata.category(chr(cp))
    if c != prev:
        starts.append(cp)
        cats.append(CATEGORIES.index(c))
        prev = c


def rows(values, per_line):
    for i in range(0, len(values), per_line):
        yield '\t' + ', '.join(str(v) for v in values[i:i + per_line]) + ','


print('// Generated by tools/gen_unicode.py from the Unicode Character Database '
      f'{unicodedata.unidata_version}. Do not edit.')
print('module xsd')
print()
print(f"pub const unicode_version = '{unicodedata.unidata_version}'")
print()
print('// The general categories, in the order the table numbers them.')
print('const category_names = [' + ', '.join(f"'{c}'" for c in CATEGORIES) + ']')
print()
print(f'// The first code point of each run of one category ({len(starts)} runs).')
print('const category_starts = [u32(0),')
print('\n'.join(rows(starts[1:], 12)))
print(']')
print()
print('// The category of each run, an index into category_names.')
print('const category_of_run = [u8(' + str(cats[0]) + '),')
print('\n'.join(rows(cats[1:], 24)))
print(']')
